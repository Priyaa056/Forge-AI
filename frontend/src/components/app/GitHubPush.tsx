// "Push to GitHub": publish the live version of a project as one commit in a new or existing repository.
// The GitHub token is typed for each push, sent once and kept only in this dialog's state.
import { ExternalLink, Github, Loader2, Lock, UploadCloud } from "lucide-react";
import { useState, type FormEvent } from "react";
import { btnGhost, btnPrimary } from "@/components/brand";
import { Alert, fieldClass } from "@/components/app/ui";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { formatWhen } from "@/lib/agents";
import type { GitHubLink, GitHubPushRequest } from "@/lib/api/types";
import { FULL_NAME, REPO_NAME, TOKEN_URL, repoSlug } from "@/lib/github";
import { cn } from "@/lib/utils";

type Target = "linked" | "new" | "existing";

type Props = {
  open: boolean;
  projectName: string;
  version: number | null;
  link?: GitHubLink | undefined;
  pending: boolean;
  error: string | null;
  onCancel: () => void;
  onSubmit: (body: GitHubPushRequest) => void;
};

export function GitHubPushDialog(props: Props) {
  const { open, pending, onCancel } = props;
  return (
    <Dialog
      open={open}
      onOpenChange={(next) => {
        if (!next && !pending) onCancel();
      }}
    >
      <DialogContent className="max-h-[92vh] w-[calc(100%-2rem)] overflow-y-auto rounded-2xl sm:max-w-xl">
        {/* Mounted only while open, so the form (and the token) is cleared every time it closes. */}
        {open && <PushForm {...props} />}
      </DialogContent>
    </Dialog>
  );
}

function PushForm({ projectName, version, link, pending, error, onCancel, onSubmit }: Props) {
  const [target, setTarget] = useState<Target>(link ? "linked" : "new");
  const [name, setName] = useState(() => repoSlug(projectName));
  const [isPrivate, setIsPrivate] = useState(true);
  const [repository, setRepository] = useState("");
  const [branch, setBranch] = useState("");
  const [message, setMessage] = useState("");
  const [token, setToken] = useState("");

  const nameValid = REPO_NAME.test(name.trim());
  const repoValid = FULL_NAME.test(repository.trim());
  const targetValid = target === "linked" || (target === "new" ? nameValid : repoValid);
  const canPush = !pending && token.trim().length > 0 && targetValid;
  const defaultMessage = `${projectName} v${version ?? "?"} - generated by FORGE AI`;

  const submit = (event: FormEvent) => {
    event.preventDefault();
    if (!canPush) return;
    const body: GitHubPushRequest =
      target === "new"
        ? { token: token.trim(), mode: "new", name: name.trim(), private: isPrivate }
        : {
            token: token.trim(),
            mode: "existing",
            repository: target === "linked" && link ? link.full_name : repository.trim(),
          };
    const chosenBranch = branch.trim() || (target === "linked" ? link?.branch : "");
    if (chosenBranch) body.branch = chosenBranch;
    if (message.trim()) body.message = message.trim();
    onSubmit(body);
  };

  const options: { value: Target; label: string; hint: string }[] = [
    ...(link
      ? [{ value: "linked" as const, label: "Linked repository", hint: link.full_name }]
      : []),
    { value: "new", label: "New repository", hint: "Created in your account" },
    { value: "existing", label: "Existing repository", hint: "owner/name you can push to" },
  ];

  return (
    <form onSubmit={submit} noValidate className="grid gap-5">
      <DialogHeader>
        <DialogTitle className="flex items-center gap-2 text-xl">
          <Github className="size-5" /> Push to GitHub
        </DialogTitle>
        <DialogDescription>
          Publishes the live version{version ? ` (v${version})` : ""} of{" "}
          <span className="font-semibold text-foreground">{projectName}</span> as one commit.
          Secrets such as <code>.env</code> files and local databases are never pushed.
        </DialogDescription>
      </DialogHeader>

      <fieldset className="grid gap-2" disabled={pending}>
        <legend className="mb-2 text-xs font-semibold text-muted-foreground">REPOSITORY</legend>
        <div
          className={cn("grid gap-2", options.length === 3 ? "sm:grid-cols-3" : "sm:grid-cols-2")}
        >
          {options.map((option) => (
            <label
              key={option.value}
              className={cn(
                "cursor-pointer rounded-xl border bg-card px-3 py-2.5 text-sm transition hover:border-primary",
                target === option.value && "border-primary bg-accent text-accent-foreground",
              )}
            >
              <input
                type="radio"
                name="github-target"
                value={option.value}
                checked={target === option.value}
                onChange={() => setTarget(option.value)}
                className="sr-only"
              />
              <span className="block font-semibold">{option.label}</span>
              <span className="block truncate text-xs text-muted-foreground">{option.hint}</span>
            </label>
          ))}
        </div>

        {target === "linked" && link && (
          <p className="rounded-xl border bg-background px-3 py-2.5 text-xs text-muted-foreground">
            Adds a commit to{" "}
            <a
              href={link.html_url}
              target="_blank"
              rel="noopener noreferrer"
              className="font-semibold text-foreground underline-offset-2 hover:underline"
            >
              {link.full_name}
            </a>{" "}
            on <span className="font-mono">{link.branch}</span>. Last pushed
            {link.pushed_version ? ` v${link.pushed_version}` : ""} {formatWhen(link.pushed_at)}.
            Files you added on GitHub are kept.
          </p>
        )}

        {target === "new" && (
          <div className="grid gap-3 sm:grid-cols-[1fr_auto] sm:items-end">
            <label className="block text-sm font-medium">
              Repository name
              <input
                value={name}
                onChange={(e) => setName(e.target.value)}
                maxLength={100}
                aria-invalid={!nameValid}
                className={`${fieldClass} mt-1.5`}
              />
            </label>
            <label className="flex items-center gap-2 pb-3 text-sm font-medium">
              <input
                type="checkbox"
                checked={isPrivate}
                onChange={(e) => setIsPrivate(e.target.checked)}
                className="size-4 accent-[var(--primary)]"
              />
              <Lock className="size-3.5 text-muted-foreground" /> Private
            </label>
            {!nameValid && (
              <p className="text-xs text-destructive sm:col-span-2">
                Use letters, numbers, “-”, “_” and “.” only.
              </p>
            )}
          </div>
        )}

        {target === "existing" && (
          <label className="block text-sm font-medium">
            Repository
            <input
              value={repository}
              onChange={(e) => setRepository(e.target.value)}
              maxLength={140}
              placeholder="owner/repository"
              autoComplete="off"
              spellCheck={false}
              className={`${fieldClass} mt-1.5`}
            />
            <span className="mt-1 block text-xs font-normal text-muted-foreground">
              The app's files are added on top of what is already there; nothing else is deleted.
            </span>
          </label>
        )}
      </fieldset>

      <fieldset className="grid gap-3 sm:grid-cols-2" disabled={pending}>
        <label className="block text-sm font-medium">
          Branch <span className="font-normal text-muted-foreground">(optional)</span>
          <input
            value={branch}
            onChange={(e) => setBranch(e.target.value)}
            maxLength={200}
            placeholder={
              target === "linked" && link
                ? link.branch
                : target === "new"
                  ? "main"
                  : "default branch"
            }
            autoComplete="off"
            spellCheck={false}
            className={`${fieldClass} mt-1.5`}
          />
        </label>
        <label className="block text-sm font-medium">
          Commit message <span className="font-normal text-muted-foreground">(optional)</span>
          <input
            value={message}
            onChange={(e) => setMessage(e.target.value)}
            maxLength={2000}
            placeholder={defaultMessage}
            className={`${fieldClass} mt-1.5`}
          />
        </label>
      </fieldset>

      <label className="block text-sm font-medium" htmlFor="github-token">
        GitHub access token
        <input
          id="github-token"
          type="password"
          value={token}
          onChange={(e) => setToken(e.target.value)}
          autoComplete="off"
          spellCheck={false}
          disabled={pending}
          placeholder="ghp_… or github_pat_…"
          className={`${fieldClass} mt-1.5 font-mono`}
        />
        <span className="mt-1.5 block text-xs font-normal text-muted-foreground">
          Used for this push only. FORGE AI does not save it. Needs the <code>repo</code> scope
          (fine-grained: Contents and Administration read/write).{" "}
          <a
            href={TOKEN_URL}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-0.5 font-semibold text-primary hover:underline"
          >
            Create a token <ExternalLink className="size-3" />
          </a>
        </span>
      </label>

      {error && <Alert>{error}</Alert>}

      <DialogFooter className="gap-2">
        <button type="button" className={btnGhost} onClick={onCancel} disabled={pending}>
          Cancel
        </button>
        <button type="submit" className={btnPrimary} disabled={!canPush}>
          {pending ? (
            <Loader2 className="size-4 animate-spin" />
          ) : (
            <UploadCloud className="size-4" />
          )}
          {pending ? "Pushing…" : "Push"}
        </button>
      </DialogFooter>
    </form>
  );
}
