"""Deploy Agent writer: Docker, Docker Compose (PostgreSQL), environment template and README."""

from typing import Dict, List

from backend.codegen.blueprint import Blueprint
from backend.codegen.project_files import GeneratedProject

AGENT = "deploy"

REQUIRED_ENV = ["DATABASE_URL", "SECRET_KEY", "ADMIN_EMAIL", "ADMIN_PASSWORD", "CORS_ORIGINS"]

BACKEND_DOCKERFILE = """FROM python:3.12-slim
WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY app ./app
COPY migrations ./migrations
EXPOSE 8000
HEALTHCHECK --interval=15s --timeout=5s --retries=5 CMD python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health')"
CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]
"""

FRONTEND_DOCKERFILE = """FROM node:20-alpine AS build
WORKDIR /app
COPY package.json ./
RUN npm install --no-audit --no-fund
COPY . .
RUN npm run build

FROM nginx:1.27-alpine
COPY nginx.conf /etc/nginx/conf.d/default.conf
COPY --from=build /app/dist /usr/share/nginx/html
EXPOSE 80
"""

NGINX_CONF = """server {
  listen 80;
  root /usr/share/nginx/html;
  index index.html;

  location /api/ {
    proxy_pass http://backend:8000;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
  }

  location /health {
    proxy_pass http://backend:8000/health;
  }

  location / {
    try_files $uri $uri/ /index.html;
  }
}
"""

DOCKERIGNORE = """node_modules
dist
__pycache__
*.pyc
.pytest_cache
*.db
.env
"""

GITIGNORE = """.env
*.db
__pycache__/
*.pyc
.pytest_cache/
node_modules/
dist/
.forge_runtime/
"""


def render_compose(bp: Blueprint) -> str:
    return f"""# {bp.project_name} - generated by FORGE AI Deploy Agent
# Usage: cp .env.example .env  (then edit the secrets)  &&  docker compose up --build
services:
  db:
    image: postgres:16-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: ${{POSTGRES_USER:-app}}
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:?Set POSTGRES_PASSWORD in .env}}
      POSTGRES_DB: ${{POSTGRES_DB:-app}}
    volumes:
      - db_data:/var/lib/postgresql/data
      - ./backend/migrations/001_initial_schema.sql:/docker-entrypoint-initdb.d/001_initial_schema.sql:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U ${{POSTGRES_USER:-app}} -d ${{POSTGRES_DB:-app}}"]
      interval: 5s
      timeout: 5s
      retries: 10

  backend:
    build: ./backend
    restart: unless-stopped
    depends_on:
      db:
        condition: service_healthy
    environment:
      DATABASE_URL: postgresql+psycopg2://${{POSTGRES_USER:-app}}:${{POSTGRES_PASSWORD}}@db:5432/${{POSTGRES_DB:-app}}
      SECRET_KEY: ${{SECRET_KEY:?Set SECRET_KEY in .env}}
      ADMIN_EMAIL: ${{ADMIN_EMAIL:-admin@example.com}}
      ADMIN_PASSWORD: ${{ADMIN_PASSWORD:?Set ADMIN_PASSWORD in .env}}
      CORS_ORIGINS: ${{CORS_ORIGINS:-http://localhost:8080}}
    ports:
      - "8000:8000"

  frontend:
    build: ./frontend
    restart: unless-stopped
    depends_on:
      - backend
    ports:
      - "8080:80"

volumes:
  db_data:
"""


def render_env_example(bp: Blueprint) -> str:
    return f"""# {bp.project_name} environment template (generated by FORGE AI Deploy Agent)
# Copy to .env and replace every value marked CHANGE_ME. Never commit .env.

# PostgreSQL (docker compose)
POSTGRES_USER=app
POSTGRES_PASSWORD=CHANGE_ME
POSTGRES_DB=app

# Backend
# For local runs without Docker you may use SQLite: DATABASE_URL=sqlite:///./app.db
DATABASE_URL=postgresql+psycopg2://app:CHANGE_ME@localhost:5432/app
SECRET_KEY=CHANGE_ME_TO_A_LONG_RANDOM_STRING
ACCESS_TOKEN_EXPIRE_MINUTES=60
CORS_ORIGINS=http://localhost:5173,http://localhost:8080

# First administrator account (created on start-up if it does not exist)
ADMIN_EMAIL=admin@example.com
ADMIN_PASSWORD=CHANGE_ME
"""


def render_readme(bp: Blueprint, api_spec: Dict, auth_spec: Dict, qa_summary: Dict, manifest: Dict[str, Dict]) -> str:
    entity_rows = "\n".join(
        f"| {e.name} | `{e.table}` | {e.access} | " + ", ".join(f"`{f.name}`" for f in e.editable_fields) + " |"
        for e in bp.entities
    )
    endpoint_rows = "\n".join(
        f"| {ep['method']} | `{ep['path']}` | {', '.join(ep.get('required_roles') or ['public'])} | {ep['summary']} |"
        for ep in api_spec.get("endpoints", [])
    )
    auth_rows = "\n".join(
        f"| {ep['method']} | `{ep['path']}` | {ep['description']} |" for ep in auth_spec.get("auth_endpoints", [])
    )
    role_rows = "\n".join(
        f"| {r['role_name']} | {', '.join(r['permissions'][:12])}{' …' if len(r['permissions']) > 12 else ''} |"
        for r in auth_spec.get("rbac_roles", [])
    )
    owners: Dict[str, int] = {}
    for meta in manifest.values():
        owners[meta.get("agent", "?")] = owners.get(meta.get("agent", "?"), 0) + 1
    owner_rows = "\n".join(f"| {agent} | {count} |" for agent, count in sorted(owners.items()))
    features = "\n".join(f"- {f}" for f in bp.features)
    qa_line = (f"{qa_summary.get('tests_passed', 0)}/{qa_summary.get('tests_run', 0)} generated API tests passed"
               if qa_summary else "see qa_report.json")
    return f"""# {bp.project_name}

{bp.description}

Generated by **FORGE AI** (PM → UI → Backend → Database → Auth → QA → Deploy agents). QA result: {qa_line}.

## Features
{features}

## Data model
| Entity | Table | Access policy | Editable fields |
|---|---|---|---|
{entity_rows}

Access policies: **owner** = users see/manage only their own records (admins see all); **admin_managed** = admins write, signed-in users read; **shared** = all signed-in users read/write, admins delete.

## Roles and permissions
| Role | Permissions |
|---|---|
{role_rows}

## API
Authentication:

| Method | Path | Description |
|---|---|---|
{auth_rows}

Resources:

| Method | Path | Roles | Summary |
|---|---|---|---|
{endpoint_rows}

Interactive docs: `http://localhost:8000/docs`.

## Run locally (no Docker)
```bash
cd backend
pip install -r requirements.txt
# SQLite is used when DATABASE_URL is not set
export SECRET_KEY=dev-secret ADMIN_EMAIL=admin@example.com ADMIN_PASSWORD=ChangeMe123
uvicorn app.main:app --reload --port 8000
```
```bash
cd frontend
npm install
npm run dev        # http://localhost:5173 (proxies /api to :8000)
```

## Run with Docker Compose (PostgreSQL)
```bash
cp .env.example .env   # edit the CHANGE_ME values
docker compose up --build
# frontend: http://localhost:8080   backend: http://localhost:8000/docs
```

## Tests
```bash
cd backend
pytest
```

## Generated files by agent
| Agent | Files |
|---|---|
{owner_rows}

See `forge_manifest.json` for the per-file ownership and checksums.
"""


def write_deploy_files(bp: Blueprint, project: GeneratedProject, api_spec: Dict, auth_spec: Dict, qa_summary: Dict) -> List[str]:
    project.write("backend/Dockerfile", BACKEND_DOCKERFILE, AGENT)
    project.write("backend/.dockerignore", DOCKERIGNORE, AGENT)
    project.write("frontend/Dockerfile", FRONTEND_DOCKERFILE, AGENT)
    project.write("frontend/.dockerignore", DOCKERIGNORE, AGENT)
    project.write("frontend/nginx.conf", NGINX_CONF, AGENT)
    project.write("docker-compose.yml", render_compose(bp), AGENT)
    project.write(".env.example", render_env_example(bp), AGENT)
    project.write(".gitignore", GITIGNORE, AGENT)
    project.write("README.md", render_readme(bp, api_spec, auth_spec, qa_summary, project.manifest), AGENT)
    return project.files_by_agent(AGENT)
