def _state_prefix(state: str) -> str:
    return state.split("_")[0][:5]


def transition_date_fields(entity: BEntity, to_state: str) -> List[List[str]]:
    """Date fields that record when a record reached a state (discharged -> discharged_on/discharge_date)."""
    prefix = _state_prefix(to_state)
    if len(prefix) < 4:
        return []
    out = []
    for f in entity.editable_fields:
        if f.kind in ("date", "datetime") and f.name.split("_")[0][:5] == prefix:
            out.append([f.name, f.kind])
    return out[:1]


def entity_rule_config(bp: Blueprint, e: BEntity) -> Dict:
    """Configuration literals for one entity router."""
    date_order, computed, unique, allocations = [], [], [], []
    status = e.get_field("status")
    for r in bp.rules_for(e.name):
        kind, fields = r.get("kind"), r.get("fields") or []
        if kind == "date_order" and len(fields) == 2 and all(e.get_field(f) for f in fields):
            message = r.get("description") or f"{humanize(fields[1])} cannot be before {humanize(fields[0]).lower()}"
            date_order.append([fields[0], fields[1], message])
        elif kind == "computed" and len(fields) == 3 and all(e.get_field(f) for f in fields):
            computed.append(fields)
        elif kind == "unique_together" and len(fields) >= 2 and all(e.get_field(f) for f in fields):
            ignored = [s for s in (status.enum_values if status else []) if s in CANCEL_STATES]
            labels = ", ".join(e.get_field(f).label.lower() for f in fields)
            message = f"A {e.label.lower()} already exists for the same {labels}."
            unique.append([fields, "status" if ignored else None, ignored, message])
        elif kind == "allocation" and fields and e.get_field(fields[0]):
            params = r.get("params") or {}
            resource = params.get("resource")
            try:
                target = bp.entity(resource)
            except KeyError:
                continue
            allocations.append({
                "field": fields[0], "resource": resource, "resource_field": "status",
                "available": params.get("available"), "occupied": params.get("occupied"),
                "release": list(params.get("release_states") or []),
                "status_field": "status" if status else None, "resource_label": target.label.capitalize(),
            })
    workflow = bp.workflows.get(e.name)
    transitions = {}
    if workflow:
        for t in workflow.get("transitions", []):
            transitions[t["action"]] = {"label": t["label"], "from": t.get("from_states") or [], "to": t["to_state"],
                                        "dates": transition_date_fields(e, t["to_state"])}
    return {"date_order": date_order, "computed": computed, "unique": unique, "allocations": allocations,
            "workflow_field": (workflow or {}).get("field", "status"), "transitions": transitions}


def py_literal(value) -> str:
    return json.dumps(value, indent=4).replace("true", "True").replace("false", "False").replace("null", "None")


