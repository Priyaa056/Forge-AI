def _date_field(e: BEntity, preferred: Optional[str] = None) -> str:
    if preferred and e.get_field(preferred):
        return preferred
    for f in e.fields:
        if f.kind in ("date", "datetime") and f.name != "created_at":
            return f.name
    return "created_at"


def entity_catalog(bp: Blueprint) -> Dict[str, Dict]:
    catalog = {}
    for e in bp.entities:
        module = bp.module_of(e.name)
        workflow = bp.workflows.get(e.name) or {}
        catalog[e.name] = {
            "label": e.label.capitalize(), "plural": e.plural_label.capitalize(), "scoped": e.owner_scoped,
            "display": e.display_field, "date_field": _date_field(e),
            "path": (module.path + (f"?tab={e.name}" if len(module.entities) > 1 else "")) if module else "/",
            "terminal": list(workflow.get("terminal") or []),
            "money": [f.name for f in e.fields if f.kind == "decimal" and not f.hidden],
            "enums": [f.name for f in e.enum_fields],
            "references": {f.name: f.references for f in e.reference_fields if f.references != "User"},
        }
    return catalog


