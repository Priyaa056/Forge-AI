def snapshot(obj, fields: List[str]) -> Dict:
    return {name: getattr(obj, name, None) for name in fields}


def _comparable(value):
    if isinstance(value, datetime):
        return value.replace(tzinfo=None)
    return value


def check_date_order(obj, rules) -> None:
    for start, end, message in rules:
        first, second = getattr(obj, start, None), getattr(obj, end, None)
        if first is None or second is None:
            continue
        try:
            invalid = _comparable(second) < _comparable(first)
        except TypeError:
            invalid = str(second) < str(first)
        if invalid:
            raise HTTPException(status_code=422, detail=message)


def apply_computed(obj, rules) -> None:
    for target, left, right in rules:
        total = float(getattr(obj, left, None) or 0)
        paid = float(getattr(obj, right, None) or 0)
        setattr(obj, target, round(total - paid, 2))


def check_unique_together(db, model, obj, rules) -> None:
    for fields, status_field, ignored_states, message in rules:
        values = {name: getattr(obj, name, None) for name in fields}
        if any(value is None for value in values.values()):
            continue
        if status_field and getattr(obj, status_field, None) in ignored_states:
            continue
        stmt = select(model.id).where(*[getattr(model, name) == value for name, value in values.items()])
        if getattr(obj, "id", None) is not None:
            stmt = stmt.where(model.id != obj.id)
        if status_field and ignored_states:
            column = getattr(model, status_field)
            stmt = stmt.where(or_(column.is_(None), column.not_in(list(ignored_states))))
        if db.scalar(stmt.limit(1)) is not None:
            raise HTTPException(status_code=409, detail=message)


def _held(values: Optional[Dict], rule: Dict):
    if not values:
        return None
    ref = values.get(rule["field"])
    if ref is None:
        return None
    status_field = rule.get("status_field")
    if status_field and values.get(status_field) in rule["release"]:
        return None
    return ref


def apply_allocations(db, before: Optional[Dict], after: Optional[Dict], rules, models) -> None:
    """Allocate/release resources: occupied while a record holds them, available again afterwards."""
    for rule in rules:
        old, new = _held(before, rule), _held(after, rule)
        if old == new:
            continue
        model = models[rule["resource"]]
        field = rule["resource_field"]
        if old is not None:
            resource = db.get(model, old)
            if resource is not None and getattr(resource, field) == rule["occupied"]:
                setattr(resource, field, rule["available"])
        if new is not None:
            resource = db.get(model, new)
            if resource is None:
                raise HTTPException(status_code=422, detail=f"{rule['field']}: {rule['resource_label']} {new} does not exist")
            current = getattr(resource, field)
            if current != rule["available"]:
                state = str(current).replace("_", " ")
                raise HTTPException(status_code=409,
                                    detail=f"{rule['resource_label']} #{new} is not available (currently {state}).")
            setattr(resource, field, rule["occupied"])


