def render_seed_data(bp: Blueprint, allocations: Dict[str, List[Dict]]) -> str:
    order = [e.name for e in bp.entities]
    # parents before children
    ordered: List[str] = []
    pending = list(order)
    while pending:
        progressed = False
        for name in list(pending):
            e = bp.entity(name)
            deps = {f.references for f in e.reference_fields if f.references in order and f.references != name}
            if deps <= set(ordered):
                ordered.append(name)
                pending.remove(name)
                progressed = True
        if not progressed:
            ordered.extend(pending)
            break
    fields = {}
    computed = {}
    resources = {rule["resource"]: rule["available"] for rules in allocations.values() for rule in rules}
    for e in bp.entities:
        computed_targets = {r["fields"][0] for r in bp.rules_for(e.name, "computed")}
        specs = []
        for f in e.editable_fields:
            if f.name in computed_targets:
                continue
            spec = {"name": f.name, "kind": f.kind, "label": f.label, "references": f.references,
                    "values": f.enum_values, "min": f.min_value, "max": f.max_value,
                    "person": _person_entity(e), "entity_label": e.label.capitalize()}
            if f.kind == "enum" and f.name == "status" and e.name in resources:
                spec["values"] = [resources[e.name]]  # allocatable resources start available
            elif f.kind == "enum" and f.name == "status" and e.name in bp.workflows:
                # demo records start in the open states more often than in terminal ones
                terminal = set(bp.workflows[e.name].get("terminal") or [])
                spec["values"] = [v for v in f.enum_values if v not in terminal] * 2 + [v for v in f.enum_values if v in terminal]
            specs.append(spec)
        state_dates = {}
        for t in (bp.workflows.get(e.name) or {}).get("transitions", []):
            for name, _kind in transition_date_fields(e, t["to_state"]):
                state_dates[name] = t["to_state"]
        fields[e.name] = {"owner": e.owner_scoped, "fields": specs, "state_dates": state_dates}
        computed[e.name] = [r["fields"] for r in bp.rules_for(e.name, "computed") if len(r["fields"]) == 3]
    seeds = {}
    for name, rows in bp.seed_records.items():
        e = bp.entity(name)
        valid = []
        for row in rows:
            row = {k: v for k, v in row.items() if e.get_field(k)}
            required = [f for f in e.editable_fields if f.required and f.name not in row and f.default is None]
            for f in required:  # fill other required fields so the explicit records can be stored
                if f.kind == "enum":
                    row[f.name] = f.enum_values[0]
                elif f.kind in ("string", "text"):
                    row[f.name] = row.get(e.display_field, f.label)
            if row:
                valid.append(row)
        if valid:
            seeds[name] = valid
    demo_note = ("generated on first start because the prompt asked for sample data." if bp.demo_data
                 else "not requested by the prompt (disabled).")
    return (SEED_PY
            .replace("__DEMO_NOTE__", demo_note)
            .replace("__IMPORTS__", ", ".join(sorted({"User", *order})))
            .replace("__MODELS__", ", ".join(f'"{n}": {n}' for n in order))
            .replace("__ORDER__", json.dumps(ordered))
            .replace("__SEEDS__", py_literal(seeds))
            .replace("__DEMO__", "True" if bp.demo_data else "False")
            .replace("__FIELDS__", py_literal(fields))
            .replace("__ALLOCATIONS__", py_literal(allocations))
            .replace("__COMPUTED__", py_literal(computed))
            .replace("__ADMIN_ROLES__", json.dumps(bp.admin_roles))
            .replace("__DISPLAY__", json.dumps({e.name: e.display_field for e in bp.entities})))
