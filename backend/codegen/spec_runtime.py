def _rows(db: Session, name: str, user: User):
    model = MODELS[name]
    stmt = select(model)
    if ENTITIES[name]["scoped"] and not is_admin(user):
        stmt = stmt.where(model.owner_id == user.id)
    return db.scalars(stmt.order_by(model.id.desc()).limit(5000)).all()


def _day(value):
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return date.fromisoformat(str(value)[:10])
    except ValueError:
        return None


def _label(name: str, row, db: Session = None) -> str:
    display = ENTITIES[name]["display"]
    value = getattr(row, display, None) if display != "id" else None
    if value not in (None, ""):
        return str(value)
    parts = []
    if db is not None:
        for field, target in list(ENTITIES[name]["references"].items())[:1]:
            ref = getattr(row, field, None)
            parent = db.get(MODELS[target], ref) if ref is not None else None
            if parent is not None:
                parts.append(_label(target, parent))
    when = getattr(row, ENTITIES[name]["date_field"], None)
    if when is not None and ENTITIES[name]["date_field"] != "created_at":
        parts.append(str(when)[:10])
    return " · ".join(parts) if parts else f"{ENTITIES[name]['label']} #{row.id}"


def _item(name: str, row, extra=None, db: Session = None) -> dict:
    return {"id": row.id, "label": _label(name, row, db), "entity": ENTITIES[name]["label"], "path": ENTITIES[name]["path"],
            **({"detail": extra} if extra is not None else {})}


def _open(name: str, row) -> bool:
    terminal = ENTITIES[name]["terminal"]
    return not terminal or getattr(row, "status", None) not in terminal


def _reference_labels(db: Session, name: str, field: str, ids) -> dict:
    target = ENTITIES[name]["references"].get(field)
    if not target or not ids:
        return {}
    model = MODELS[target]
    rows = db.scalars(select(model).where(model.id.in_(list(ids)))).all()
    return {row.id: _label(target, row) for row in rows}


def evaluate(db: Session, metric: dict, user: User) -> dict:
    kind, name, field = metric["kind"], metric.get("entity"), metric.get("field")
    params = metric.get("params") or {}
    out = {"id": metric["id"], "label": metric["label"], "kind": kind, "entity": name,
           "path": ENTITIES[name]["path"] if name in ENTITIES else None}
    today = date.today()
    if kind == "recent":
        items = []
        for entity in ENTITIES:
            for row in _rows(db, entity, user)[:8]:
                items.append((row.created_at.replace(tzinfo=None) if row.created_at else datetime.min, entity, row))
        items.sort(key=lambda item: item[0], reverse=True)
        out["items"] = [_item(entity, row, row.created_at.isoformat() if row.created_at else None, db) for _, entity, row in items[:8]]
        out["value"] = len(out["items"])
        return out
    rows = _rows(db, name, user)
    if kind == "count":
        out["value"] = len(rows)
    elif kind == "count_where":
        wanted = [v for v in str(metric.get("value") or "").split(",") if v]
        out["value"] = sum(1 for row in rows if getattr(row, field or "status", None) in wanted)
    elif kind == "count_today":
        out["value"] = sum(1 for row in rows if _day(getattr(row, field, None)) == today)
    elif kind == "upcoming":
        upcoming = [row for row in rows if (_day(getattr(row, field, None)) or date.min) >= today and _open(name, row)]
        upcoming.sort(key=lambda row: _day(getattr(row, field)))
        out["value"] = len(upcoming)
        out["items"] = [_item(name, row, str(_day(getattr(row, field))), db) for row in upcoming[:6]]
    elif kind in ("sum", "sum_month"):
        date_field = params.get("date_field") or ENTITIES[name]["date_field"]
        selected = rows if kind == "sum" else [
            row for row in rows if (_day(getattr(row, date_field, None)) or date.min).replace(day=1) == today.replace(day=1)]
        out["value"] = round(sum(float(getattr(row, field, None) or 0) for row in selected), 2)
        out["format"] = "money"
    elif kind == "average":
        values = [float(getattr(row, field)) for row in rows if getattr(row, field, None) is not None]
        out["value"] = round(sum(values) / len(values), 1) if values else 0
        out["format"] = "percent" if field == "progress" else None
    elif kind == "alert":
        rule = params.get("rule")
        if rule == "low_stock":
            hits = [row for row in rows if getattr(row, field, None) is not None and getattr(row, field) <= params.get("threshold", 10)]
            detail = lambda row: f"{getattr(row, field)} left"  # noqa: E731
        elif rule == "expiry":
            limit = today + timedelta(days=int(params.get("warning_days", 30)))
            hits = [row for row in rows if _day(getattr(row, field, None)) and _day(getattr(row, field)) <= limit]
            detail = lambda row: ("expired " if _day(getattr(row, field)) < today else "expires ") + str(_day(getattr(row, field)))  # noqa: E731
        else:  # overdue
            hits = [row for row in rows if _day(getattr(row, field, None)) and _day(getattr(row, field)) < today and _open(name, row)]
            detail = lambda row: f"due {_day(getattr(row, field))}"  # noqa: E731
        out["value"] = len(hits)
        out["items"] = [_item(name, row, detail(row), db) for row in hits[:6]]
        out["tone"] = "warning"
    elif kind == "breakdown":
        counts = Counter(getattr(row, field, None) for row in rows)
        labels = _reference_labels(db, name, field, [k for k in counts if k is not None]) if field in ENTITIES[name]["references"] else {}
        out["series"] = [{"key": str(key), "label": labels.get(key, str(key).replace("_", " ").capitalize() if key is not None else "Not set"),
                          "value": value} for key, value in counts.most_common(12)]
        out["value"] = len(rows)
    elif kind == "trend":
        date_field = params.get("date_field") or ENTITIES[name]["date_field"]
        months = []
        cursor = today.replace(day=1)
        for _ in range(6):
            months.insert(0, cursor)
            cursor = (cursor - timedelta(days=1)).replace(day=1)
        counts = Counter((_day(getattr(row, date_field, None)) or date.min).replace(day=1) for row in rows)
        out["series"] = [{"key": m.isoformat()[:7], "label": m.strftime("%b %Y"), "value": counts.get(m, 0)} for m in months]
        out["value"] = sum(point["value"] for point in out["series"])
    return out


