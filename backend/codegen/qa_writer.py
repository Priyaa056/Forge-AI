def _sample_value(f: BField, n: int):
    if f.kind == "enum":
        return f.enum_values[0]
    if f.kind == "boolean":
        return True
    if f.kind == "date":
        return "2026-01-15"
    if f.kind == "datetime":
        return "2026-01-15T10:30:00"
    if f.kind == "email":
        return f"qa{n}@example.com"
    if f.kind in ("integer",):
        low = int(f.min_value) if f.min_value is not None else 1
        high = int(f.max_value) if f.max_value is not None else low + 10
        return max(low, min(high, max(low, 3)))
    if f.kind in ("float", "decimal"):
        low = f.min_value if f.min_value is not None else 0
        high = f.max_value if f.max_value is not None else low + 100
        return round(min(high, max(low, 19.99)), 2)
    if f.kind == "text":
        return f"QA generated {f.label.lower()} {n}"
    return f"QA {f.label} {n}"


def _creator(e: BEntity) -> str:
    return "admin_headers" if e.access == "admin_managed" else "user_headers"


