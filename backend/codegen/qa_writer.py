def write_test_files(bp: Blueprint, project: GeneratedProject) -> List[str]:
    project.write("backend/tests/__init__.py", "", AGENT)
    project.write("backend/tests/conftest.py", render_conftest(bp), AGENT)
    project.write("backend/tests/factories.py", render_factories(bp), AGENT)
    project.write("backend/tests/test_auth.py", render_auth_tests(bp), AGENT)
    project.write("backend/tests/test_admin.py", render_admin_tests(bp), AGENT)
    for e in bp.entities:
        project.write(f"backend/tests/test_{e.plural_snake}.py", render_entity_tests(bp, e), AGENT)
    project.write("backend/pytest.ini", "[pytest]\ntestpaths = tests\npythonpath = tests .\n", AGENT)
    return project.files_by_agent(AGENT)
