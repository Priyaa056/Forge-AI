@app.get("/api/projects/{project_id}/runs/{run_id}/events")
def get_run_events(project_id: str, run_id: str, after: Optional[str] = None, include_logs: bool = True,
                   user: User = Depends(current_user)):
    svc = services()
    owned_project(project_id, user)
    svc["store"].load_run(project_id, run_id)
    events = [e for e in svc["runs"].pipeline_logger.read_logs_from_file() if e.run_id == run_id]
    if not include_logs:
        events = [e for e in events if e.event_type.value != "AGENT_LOG"]
    if after:
        ids = [e.event_id for e in events]
        if after in ids:
            events = events[ids.index(after) + 1:]
    return {"project_id": project_id, "run_id": run_id, "count": len(events), "events": [e.model_dump() for e in events]}


