_services: Dict[str, Any] = {}


def services():
    if "runs" not in _services:
        runs = RunManager()
        previews = PreviewManager(runs.store)

        def restart_preview_if_running(project_id: str) -> None:
            if project_id in previews.previews:
                try:
                    previews.start(project_id)
                except Exception:
                    pass

        runs.on_promoted = restart_preview_if_running
        _services.update(runs=runs, store=runs.store, previews=previews, users=UserStore())
    return _services


def reset_services() -> None:
    """Drop service singletons (used by tests that switch FORGE_WORKSPACE)."""
    if "previews" in _services:
        _services["previews"].stop_all()
    if "runs" in _services:
        _services["runs"].shutdown()
    _services.clear()


@asynccontextmanager
async def lifespan(_app: FastAPI):
    yield
    if "previews" in _services:
        _services["previews"].stop_all()


