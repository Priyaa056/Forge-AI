@app.post("/api/projects", status_code=status.HTTP_202_ACCEPTED)
def create_project(req: ProjectCreateRequest, user: User = Depends(current_user)):
    prompt = _check_prompt(req.user_prompt)
    fault = _check_fault(req.simulate_failure)
    svc = services()
    project = svc["store"].create_project(prompt, req.project_name, owner_id=user["id"])
    return svc["runs"].start_run(project["project_id"], prompt, simulate_failure=fault)


