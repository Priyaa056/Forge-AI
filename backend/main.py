# ---------------------------------------------------------------------------------------------- auth
_bearer = HTTPBearer(auto_error=False)
User = Dict[str, Any]


def current_user(credentials: Optional[HTTPAuthorizationCredentials] = Depends(_bearer)) -> User:
    if credentials is None or credentials.scheme.lower() != "bearer":
        raise HTTPException(status_code=401, detail="Not authenticated", headers={"WWW-Authenticate": "Bearer"})
    try:
        claims = decode_access_token(credentials.credentials)
    except AuthError as exc:
        raise HTTPException(status_code=401, detail=str(exc), headers={"WWW-Authenticate": "Bearer"})
    user = services()["users"].get(str(claims.get("sub")))
    if user is None:
        raise HTTPException(status_code=401, detail="Account not found", headers={"WWW-Authenticate": "Bearer"})
    return user


def owned_project(project_id: str, user: User) -> Dict[str, Any]:
    """Load a project that belongs to ``user``; other users' projects are reported as not found."""
    project = services()["store"].load_project(project_id)
    if project.get("owner_id") != user["id"]:
        raise ProjectNotFound(project_id)
    return project


class RegisterRequest(BaseModel):
    email: str = Field(..., max_length=255)
    password: str = Field(..., max_length=128)
    full_name: Optional[str] = Field(default=None, max_length=120)


class LoginRequest(BaseModel):
    email: str = Field(..., max_length=255)
    password: str = Field(..., max_length=128)


def _session(user: User) -> Dict[str, Any]:
    return {"access_token": create_access_token(user["id"], user["email"]), "token_type": "bearer",
            "expires_in": token_ttl_seconds(), "user": public_user(user)}


@app.post("/api/auth/register", status_code=status.HTTP_201_CREATED)
def register(req: RegisterRequest):
    svc = services()
    first_account = svc["users"].count() == 0
    try:
        user = svc["users"].create(req.email, req.password, req.full_name)
    except UserExists as exc:
        raise HTTPException(status_code=409, detail=str(exc))
    except InvalidUserInput as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    if first_account:
        # Projects generated before accounts existed belong to the first account on this installation.
        svc["store"].adopt_unowned_projects(user["id"])
    return _session(user)


@app.post("/api/auth/login")
def login(req: LoginRequest):
    user = services()["users"].authenticate(req.email, req.password)
    if user is None:
        raise HTTPException(status_code=401, detail="Incorrect email or password.")
    return _session(user)


@app.get("/api/auth/me")
def me(user: User = Depends(current_user)):
    return public_user(user)


# ---------------------------------------------------------------------------------------------- models
SIMULATABLE = [s.value for s in STAGE_ORDER]


class ProjectCreateRequest(BaseModel):
    user_prompt: str = Field(..., description="Natural-language application idea")
    project_name: Optional[str] = Field(default=None, max_length=80)
    simulate_failure: Optional[str] = Field(default=None, description="Test mode: inject a failure into this agent")


class RunCreateRequest(BaseModel):
    user_prompt: str
    simulate_failure: Optional[str] = None


class ProjectRollbackRequest(BaseModel):
    target_run_id: str = Field(..., description="A run that produced a stable version")
    reason: Optional[str] = Field(default=None, max_length=300)


class RollbackApiRequest(BaseModel):
    agent_name: str = Field(..., description="Stage/agent name to roll back (e.g. pm, ui, backend)")
    target_version: int = Field(..., description="Target artifact version number to restore")
    reason: Optional[str] = None
    force: bool = False


class PMRequest(BaseModel):
    user_prompt: str = Field(..., json_schema_extra={"example": "Build a task management app with categories"})


def _check_prompt(prompt: str) -> str:
    try:
        return validate_prompt(prompt)
    except PromptValidationError as exc:
        raise HTTPException(status_code=400, detail=str(exc))


def _check_fault(stage: Optional[str]) -> Optional[str]:
    if not stage:
        return None
    if not env_flag("FORGE_ALLOW_FAULT_INJECTION", True):
        raise HTTPException(status_code=400, detail="Fault injection is disabled on this server")
    if stage.lower() not in SIMULATABLE:
        raise HTTPException(status_code=400, detail=f"simulate_failure must be one of {SIMULATABLE}")
    return stage.lower()


