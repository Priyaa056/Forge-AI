# ---------------------------------------------------------------------------------------------- files
def _app_root(project_id: str, run_id: str, user: User) -> Path:
    store = services()["store"]
    owned_project(project_id, user)
    return store.current_dir(project_id) if run_id == "current" else store.app_dir(project_id, run_id)


@app.get("/api/projects/{project_id}/runs/{run_id}/files")
def list_files(project_id: str, run_id: str, user: User = Depends(current_user)):
    root = _app_root(project_id, run_id, user)
    manifest = {}
    if (root / "forge_manifest.json").is_file():
        manifest = json.loads((root / "forge_manifest.json").read_text(encoding="utf-8")).get("files", {})
    files = [{**f, "agent": manifest.get(f["path"], {}).get("agent")} for f in file_tree(root)]
    return {"project_id": project_id, "run_id": run_id, "count": len(files), "files": files}


@app.get("/api/projects/{project_id}/runs/{run_id}/files/content")
def read_file(project_id: str, run_id: str, path: str, user: User = Depends(current_user)):
    root = _app_root(project_id, run_id, user)
    target = services()["store"].safe_file(root, path)
    if target.stat().st_size > 512_000:
        raise HTTPException(status_code=413, detail="File too large to display")
    return {"path": path, "content": target.read_text(encoding="utf-8", errors="replace")}


@app.get("/api/projects/{project_id}/runs/{run_id}/specs/{agent_name}")
def read_spec(project_id: str, run_id: str, agent_name: str, user: User = Depends(current_user)):
    try:
        stage = PipelineStage(agent_name)
    except ValueError:
        raise HTTPException(status_code=404, detail="Unknown agent")
    owned_project(project_id, user)
    data = services()["store"].read_spec(project_id, run_id, STAGE_SPEC_FILES[stage])
    if data is None:
        raise HTTPException(status_code=404, detail="Specification not produced in this run")
    return data


@app.get("/api/projects/{project_id}/runs/{run_id}/download")
def download_app(project_id: str, run_id: str, user: User = Depends(current_user)):
    root = _app_root(project_id, run_id, user)
    files = file_tree(root)
    if not files:
        raise HTTPException(status_code=404, detail="No generated files for this version yet")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in files:
            zf.write(root / f["path"], arcname=f["path"])
    buffer.seek(0)
    name = f"{project_id}-{run_id}.zip"
    return StreamingResponse(buffer, media_type="application/zip",
                             headers={"Content-Disposition": f'attachment; filename="{name}"'})


# ---------------------------------------------------------------------------------------------- rollback
@app.post("/api/projects/{project_id}/rollback")
def rollback_project(project_id: str, req: ProjectRollbackRequest, user: User = Depends(current_user)):
    """Restore a previous stable version: all seven artifacts and the generated files, verified by checksum."""
    svc = services()
    owned_project(project_id, user)
    was_previewing = project_id in svc["previews"].previews
    result = svc["store"].rollback(project_id, req.target_run_id, svc["runs"].artifact_manager,
                                   svc["runs"].pipeline_logger, reason=req.reason)
    if was_previewing:
        try:
            svc["previews"].start(project_id)
            result["preview_restarted"] = True
        except Exception as exc:  # report, do not undo the rollback
            result["preview_restarted"] = False
            result["preview_error"] = str(exc)[:300]
    return result


@app.post("/api/projects/{project_id}/runs/{run_id}/rollback")
def rollback_stage_artifact(project_id: str, run_id: str, req: RollbackApiRequest, user: User = Depends(current_user)):
    """Artifact-level rollback of one agent's output (history preserved; dependency-checked)."""
    try:
        stage = PipelineStage(req.agent_name.lower())
    except ValueError:
        raise HTTPException(status_code=400, detail=f"Invalid pipeline stage/agent name '{req.agent_name}'")
    svc = services()
    owned_project(project_id, user)
    manager = RollbackManager(artifact_manager=svc["runs"].artifact_manager, pipeline_logger=svc["runs"].pipeline_logger)
    result = manager.rollback_to_version(project_id=project_id, agent_name=stage.value, target_version=req.target_version,
                                         run_id=run_id, reason=req.reason, force=req.force,
                                         schema_cls=STAGE_SCHEMA_MAP[stage])
    return result.model_dump()


