import React from 'react';
import { Eye, FileCode, FlaskConical, History, RefreshCw } from 'lucide-react';
import type { AgentEntry, AgentStatus, StageName } from '../types';
import { STAGE_META } from '../lib/stages';
import { cn, formatDuration, shortId } from '../lib/utils';
import { StatusBadge } from './ui';

interface AgentCardProps {
  stage: StageName;
  entry?: AgentEntry;
  status: AgentStatus;
  artifactId: string | null;
  simulated: boolean;
  onOpenArtifact: (artifactId: string) => void;
  onOpenVersions: (stage: StageName) => void;
}

const MODE_LABELS: Record<string, { label: string; cls: string; title: string }> = {
  llm: { label: 'LLM', cls: 'bg-violet-950/70 border-violet-800/70 text-violet-300', title: 'Generated with LLM assistance' },
  deterministic: {
    label: 'Rule-based',
    cls: 'bg-slate-800/80 border-slate-700 text-slate-300',
    title: 'Generated by prompt-driven rule-based analysis (no LLM)',
  },
  deterministic_fallback: {
    label: 'Rule-based (fallback)',
    cls: 'bg-amber-950/60 border-amber-800/70 text-amber-300',
    title: 'The LLM output was unusable, so rule-based generation was used instead',
  },
  execution: {
    label: 'Executed',
    cls: 'bg-teal-950/60 border-teal-800/70 text-teal-300',
    title: 'This agent ran real checks against the generated app',
  },
  custom_handler: { label: 'Custom', cls: 'bg-slate-800/80 border-slate-700 text-slate-300', title: 'Custom handler' },
};

const CARD_TONE: Record<AgentStatus, string> = {
  PENDING: 'border-slate-800/80',
  RUNNING: 'border-blue-600/70 shadow-blue-900/40 ring-1 ring-blue-500/30',
  RETRYING: 'border-amber-600/70 ring-1 ring-amber-500/30',
  COMPLETED: 'border-emerald-900/80',
  FAILED: 'border-rose-800/80',
  SKIPPED: 'border-slate-900 opacity-50',
};

export const AgentCard: React.FC<AgentCardProps> = ({
  stage,
  entry,
  status,
  artifactId,
  simulated,
  onOpenArtifact,
  onOpenVersions,
}) => {
  const meta = STAGE_META[stage];
  const Icon = meta.icon;
  const mode = entry?.generation_mode ? MODE_LABELS[entry.generation_mode] : undefined;
  const attempts = entry?.attempts ?? 0;
  const clickable = !!artifactId;
  const active = status === 'RUNNING' || status === 'RETRYING';

  const open = () => artifactId && onOpenArtifact(artifactId);

  return (
    <div
      role={clickable ? 'button' : undefined}
      tabIndex={clickable ? 0 : undefined}
      onClick={open}
      onKeyDown={(e) => {
        if (clickable && (e.key === 'Enter' || e.key === ' ')) {
          e.preventDefault();
          open();
        }
      }}
      title={clickable ? 'Open artifact viewer' : undefined}
      className={cn(
        'glass-panel rounded-2xl p-4 border transition-all flex flex-col justify-between shadow-lg group min-w-0',
        CARD_TONE[status],
        clickable && 'cursor-pointer hover:border-slate-600 focus:outline-none focus:ring-2 focus:ring-blue-500',
      )}
    >
      <div>
        <div className="flex items-start justify-between gap-2 mb-3">
          <div className="flex items-center gap-2.5 min-w-0">
            <div className="p-2 rounded-xl bg-slate-900 border border-slate-800 shrink-0">
              <Icon className={cn('w-5 h-5', meta.accent)} />
            </div>
            <div className="min-w-0">
              <h3 className="text-sm font-bold text-slate-100 group-hover:text-blue-300 transition-colors truncate">
                {meta.index}. {meta.title}
              </h3>
              <p className="text-[11px] text-slate-400 truncate">{meta.description}</p>
            </div>
          </div>
        </div>

        <div className="flex flex-wrap items-center gap-1.5 text-[10px] font-mono">
          <StatusBadge status={status} size="xs" className="shrink-0" />
          {mode ? (
            <span className={cn('px-1.5 py-0.5 rounded border', mode.cls)} title={mode.title}>
              {mode.label}
            </span>
          ) : entry?.generation_mode ? (
            <span className="px-1.5 py-0.5 rounded border bg-slate-800/80 border-slate-700 text-slate-300">
              {entry.generation_mode}
            </span>
          ) : null}
          {attempts > 0 && (
            <span
              className={cn(
                'px-1.5 py-0.5 rounded border inline-flex items-center gap-1',
                attempts > 1
                  ? 'bg-amber-950/60 border-amber-800/70 text-amber-300'
                  : 'bg-slate-900 border-slate-800 text-slate-400',
              )}
              title="Attempts (self-healing retries count as extra attempts)"
            >
              <RefreshCw className="w-3 h-3" />
              {attempts} attempt{attempts === 1 ? '' : 's'}
            </span>
          )}
          {(entry?.generated_files ?? 0) > 0 && (
            <span className="px-1.5 py-0.5 rounded border bg-slate-900 border-slate-800 text-slate-400 inline-flex items-center gap-1">
              <FileCode className="w-3 h-3" />
              {entry?.generated_files} file{entry?.generated_files === 1 ? '' : 's'}
            </span>
          )}
          {simulated && (
            <span
              className="px-1.5 py-0.5 rounded border bg-amber-950/60 border-amber-800/70 text-amber-300 inline-flex items-center gap-1"
              title="Test mode: a failure is injected into this agent"
            >
              <FlaskConical className="w-3 h-3" />
              simulated failure
            </span>
          )}
        </div>

        {entry?.error && (
          <div className="mt-3 p-2.5 rounded-xl bg-rose-950/60 border border-rose-800/60 text-rose-200 text-[11px] font-mono break-words max-h-32 overflow-y-auto">
            {entry.error}
          </div>
        )}
      </div>

      <div className="pt-3 border-t border-slate-800/60 mt-3 flex items-center justify-between gap-2 text-[11px] font-mono">
        <span className="text-slate-400">
          {active ? 'Running for ' : 'Duration '}
          <span className={cn('font-semibold', active ? 'text-blue-300' : 'text-slate-200')}>
            {formatDuration(entry?.duration_ms)}
          </span>
        </span>
        <div className="flex items-center gap-1.5">
          {artifactId ? (
            <span className="inline-flex items-center gap-1 text-blue-300" title={artifactId}>
              <Eye className="w-3.5 h-3.5" />
              {shortId(artifactId, 10)}
            </span>
          ) : (
            <span className="text-slate-600 italic">no artifact</span>
          )}
          <button
            type="button"
            onClick={(e) => {
              e.stopPropagation();
              onOpenVersions(stage);
            }}
            className="p-1 rounded-md text-slate-500 hover:text-amber-300 hover:bg-slate-800"
            title="Artifact versions & stage rollback (advanced)"
            aria-label={`Artifact versions for ${meta.title}`}
          >
            <History className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>
    </div>
  );
};
