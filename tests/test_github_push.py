def live_project(client, files: Dict[str, bytes], project_id: str = None) -> str:
    """A project whose live version consists of ``files`` (a new version each call)."""
    from backend import main

    store = main.services()["store"]
    if project_id is None:
        owner = client.get("/api/auth/me").json()["id"]
        project_id = store.create_project("Build a farm management app", "Farm App", owner_id=owner)["project_id"]
    project = store.load_project(project_id)
    run_id = f"run_test{len(project['runs']) + 1}"
    app_dir = store.register_run(project_id, run_id, "prompt", {}) / "app"
    for rel, data in files.items():
        (app_dir / rel).parent.mkdir(parents=True, exist_ok=True)
        (app_dir / rel).write_bytes(data)
    project = store.load_project(project_id)
    project["current_version"] = (project.get("current_version") or 0) + 1
    project["current_run_id"] = run_id
    store.save_project(project)
    return project_id


def push(client, project_id, **body):
    return client.post(f"/api/projects/{project_id}/github/push", json={"token": TOKEN, **body})


def test_push_real_build_to_new_private_repository(client, github, isolated_workspace):
    created = client.post("/api/projects", json={"user_prompt": TASK_PROMPT}).json()
    pid = created["project_id"]
    assert wait_for(client, pid, created["run_id"])["execution_status"] == "COMPLETED"
    snapshot = isolated_workspace / "projects" / pid / "runs" / created["run_id"] / "app"
    (snapshot / ".env").write_text("SECRET_KEY=do-not-push\n")
    (snapshot / "backend" / "app.db").write_bytes(b"SQLite format 3\x00")

    response = push(client, pid, mode="new", name="task-app")
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["pushed"] and body["changed"] and body["created_repository"]
    assert body["full_name"] == "forge-tester/task-app" and body["branch"] == "main"
    assert body["html_url"] == "https://github.com/forge-tester/task-app"

    repo = github.repos["forge-tester/task-app"]
    assert repo["private"] is True and "generated by FORGE AI" in repo["description"]
    on_github = github.files("forge-tester/task-app")
    expected = {f["path"] for f in client.get(f"/api/projects/{pid}/runs/current/files").json()["files"]}
    assert set(on_github) == expected  # the app's files replace the auto-created README
    assert ".env" not in on_github and "backend/app.db" not in on_github
    assert ".env.example" in on_github and "README.md" in on_github
    assert on_github["backend/app/main.py"] == (snapshot / "backend" / "app" / "main.py").read_bytes()
    commit = github.commit_of("forge-tester/task-app")
    assert len(commit["parents"]) == 1 and "generated by FORGE AI" in commit["message"]

    # the project remembers the repository, never the token
    link = client.get(f"/api/projects/{pid}").json()["github"]
    assert link["full_name"] == "forge-tester/task-app" and link["pushed_version"] == 1
    assert link["last_commit"] == body["commit_sha"] and "pushed_paths" not in link
    assert TOKEN not in (isolated_workspace / "projects" / pid / "project.json").read_text()
    assert TOKEN not in response.text
    for log in isolated_workspace.rglob("*.jsonl"):
        assert TOKEN not in log.read_text(encoding="utf-8", errors="ignore")
    assert all(auth == f"Bearer {TOKEN}" for auth in github.seen_auth)


def test_update_push_keeps_github_edits_and_removes_stale_files(client, github):
    pid = live_project(client, {"README.md": b"# Farm\n", "app.py": b"v1\n", "old.txt": b"gone soon\n",
                                "static/logo.png": b"\x89PNG\r\n\x1a\n\x00\x01binary"})
    first = push(client, pid, mode="new", name="farm-app", private=False)
    assert first.status_code == 200, first.text
    assert github.repos["forge-tester/farm-app"]["private"] is False
    assert github.files("forge-tester/farm-app")["static/logo.png"] == b"\x89PNG\r\n\x1a\n\x00\x01binary"
    github.commit_file("forge-tester/farm-app", "NOTES.md", "added on GitHub\n")
    head_before = github.repos["forge-tester/farm-app"]["refs"]["main"]

    live_project(client, {"README.md": b"# Farm\n", "app.py": b"v2\n", "static/logo.png": b"\x89PNG\r\n\x1a\n\x00\x01binary"},
                 project_id=pid)
    second = push(client, pid, mode="existing", repository="forge-tester/farm-app", message="Version 2")
    assert second.status_code == 200, second.text
    body = second.json()
    assert body["changed"] and not body["created_repository"] and body["removed"] == ["old.txt"]
    files = github.files("forge-tester/farm-app")
    assert files["app.py"] == b"v2\n" and "old.txt" not in files
    assert files["NOTES.md"] == b"added on GitHub\n"  # the user's own commit is kept
    commit = github.commit_of("forge-tester/farm-app")
    assert commit["parents"] == [head_before] and commit["message"] == "Version 2"
    assert client.get(f"/api/projects/{pid}").json()["github"]["pushed_version"] == 2

    # nothing new to push: no empty commit
    third = push(client, pid, mode="existing", repository="forge-tester/farm-app")
    assert third.status_code == 200 and third.json()["changed"] is False
    assert github.repos["forge-tester/farm-app"]["refs"]["main"] == body["commit_sha"]


def test_push_to_new_branch_and_to_empty_repository(client, github):
    pid = live_project(client, {"README.md": b"# Farm\n", "app.py": b"print('hi')\n"})
    github.add_repo("forge-tester/existing", files={"README.md": "# Mine\n", "LICENSE": "MIT\n"})
    main_head = github.repos["forge-tester/existing"]["refs"]["main"]

    response = push(client, pid, mode="existing", repository="forge-tester/existing", branch="forge-ai/farm")
    assert response.status_code == 200, response.text
    assert response.json()["branch"] == "forge-ai/farm"
    assert github.repos["forge-tester/existing"]["refs"]["main"] == main_head  # main untouched
    branch_files = github.files("forge-tester/existing", "forge-ai/farm")
    assert branch_files["README.md"] == b"# Farm\n" and branch_files["LICENSE"] == b"MIT\n"

    github.add_repo("forge-tester/blank", empty=True)
    response = push(client, pid, mode="existing", repository="forge-tester/blank")
    assert response.status_code == 200, response.text
    assert github.files("forge-tester/blank")["app.py"] == b"print('hi')\n"


def test_errors_are_explained_and_never_log_the_user_out(client, github):
    pid = live_project(client, {"app.py": b"x\n"})

    bad = client.post(f"/api/projects/{pid}/github/push", json={"token": "wrong-token", "mode": "new", "name": "a"})
    assert bad.status_code == 400 and "rejected the access token" in bad.json()["detail"]
    assert "wrong-token" not in bad.text
    assert client.get("/api/auth/me").status_code == 200  # the platform session is untouched

    github.add_repo("forge-tester/taken")
    taken = push(client, pid, mode="new", name="taken")
    assert taken.status_code == 409 and "already have a repository named 'taken'" in taken.json()["detail"]

    missing = push(client, pid, mode="existing", repository="forge-tester/nope")
    assert missing.status_code == 400 and "was not found" in missing.json()["detail"]

    github.add_repo("someone/public-app", private=False)
    denied = push(client, pid, mode="existing", repository="someone/public-app")
    assert denied.status_code == 400 and "cannot push to someone/public-app" in denied.json()["detail"]

    for body, text in [({"mode": "new", "name": "bad name!"}, "Repository names"),
                       ({"mode": "existing", "repository": "no-slash"}, "owner/name"),
                       ({"mode": "new", "name": "ok", "branch": "../main"}, "not a valid branch")]:
        invalid = push(client, pid, **body)
        assert invalid.status_code == 400 and text in invalid.json()["detail"], invalid.text
    assert len(github.repos) == 2  # nothing was created by the failed attempts

    def offline(_request):
        raise httpx.ConnectError("offline")

    github_publisher.set_transport_for_tests(httpx.MockTransport(offline))
    unreachable = push(client, pid, mode="new", name="later")
    assert unreachable.status_code == 502 and "Could not reach GitHub" in unreachable.json()["detail"]


def test_branch_moved_on_github_during_push_is_not_overwritten(client, github):
    pid = live_project(client, {"app.py": b"v1\n"})
    github.add_repo("forge-tester/busy")
    inner = github.transport()

    def racing(request: httpx.Request) -> httpx.Response:
        if request.method == "PATCH":
            github.commit_file("forge-tester/busy", "racing.txt", "pushed by someone else\n")
        return inner.handle_request(request)

    github_publisher.set_transport_for_tests(httpx.MockTransport(racing))
    response = push(client, pid, mode="existing", repository="forge-tester/busy")
    assert response.status_code == 409 and "changed on GitHub while pushing" in response.json()["detail"]
    assert "racing.txt" in github.files("forge-tester/busy") and "app.py" not in github.files("forge-tester/busy")


def test_push_needs_a_live_version_an_owner_and_one_push_at_a_time(client, github, isolated_workspace):
    from backend import main

    store = main.services()["store"]
    owner = client.get("/api/auth/me").json()["id"]
    empty = store.create_project("Build an app", owner_id=owner)["project_id"]
    response = push(client, empty, mode="new", name="x")
    assert response.status_code == 409 and "no live version" in response.json()["detail"]

    other = store.create_project("Build an app", owner_id="someone-else")["project_id"]
    assert push(client, other, mode="new", name="x").status_code == 404

    pid = live_project(client, {"app.py": b"x\n"})
    github_publisher._active_pushes.add(pid)
    try:
        busy = push(client, pid, mode="new", name="x")
        assert busy.status_code == 409 and "already in progress" in busy.json()["detail"]
    finally:
        github_publisher._active_pushes.discard(pid)
    assert github.repos == {}

    from backend.main import app

    with TestClient(app) as anonymous:
        assert anonymous.post(f"/api/projects/{pid}/github/push", json={"token": TOKEN}).status_code == 401


def test_secret_and_build_files_are_never_collected(tmp_path: Path):
    for rel, data in {"app.py": "x", ".env": "S=1", "backend/.env.local": "S=2", ".env.example": "S=CHANGE_ME",
                      "data/app.db": "db", "keys/server.pem": "k", "node_modules/a/index.js": "x",
                      "frontend/dist/index.html": "x", "pkg/__pycache__/m.pyc": "x"}.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(data)
    assert sorted(p for p, _ in github_publisher.collect_files(tmp_path)) == [".env.example", "app.py"]
    assert json.dumps(github_publisher.PushResult("o/r", "u", "main", "s", "c", False, True, 1).link(3))
